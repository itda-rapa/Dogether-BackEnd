CREATE TABLE setlog_reactions (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    setlog_id       BIGINT       NOT NULL REFERENCES setlogs(id),
    reactor_pet_id  BIGINT       NOT NULL REFERENCES pets(id),
    type            VARCHAR(20)  NOT NULL,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_setlog_reaction_type CHECK (type IN ('CUTE', 'LIKE')),
