    meeting_card_id  BIGINT       NOT NULL REFERENCES meeting_cards(id),
    pet_id           BIGINT       NOT NULL REFERENCES pets(id),
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_meeting_participant UNIQUE (meeting_card_id, pet_id)
